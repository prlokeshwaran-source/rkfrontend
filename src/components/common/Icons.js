export const getStatusIcon = (status) => {
  const iconMap = {
    active: Check,
    approved: Check,
    completed: Check,
    received: Check,
    pending: Clock,
    inactive: X,
    processing: ShoppingCart,
    cancelled: X,
    rejected: X,
  };
  return iconMap[status?.toLowerCase()] || Clock;
};

export const getActivityIcon = (type) => {
  const iconMap = {
    member: Users,
    order: Package,
    payment: CreditCard,
    approval: ClipboardCheck,
  };
  return iconMap[type] || Bell;
};

